import {readFile, writeFile} from 'node:fs/promises'

import {compile, type JSONSchema} from 'json-schema-to-typescript'

type Definition = {key: string; schema: JSONSchema; levels: string[]; bigList?: object}

const dir = new URL('../src/preferences/', import.meta.url)
// zod's `z.never()` becomes `{not: {}}`, which json-schema-to-typescript would type as an object
const definitions: Definition[] = JSON.parse(
  await readFile(new URL('definitions.json', dir), 'utf8'),
  (_key, value) => (isNever(value) ? {tsType: 'never'} : value),
)

const valueKeys = definitions.filter(({bigList}) => !bigList)
const itemKeys = definitions.filter(({bigList}) => bigList)

const output = [
  "// Generated by `pnpm generate:preferences` from definitions.json, which Cellar's release workflow updates. Don't edit by hand",
  "import {type ItemKeyInfos, type KeyInfos} from './registry'",
  await toInterface('Values', valueKeys),
  // A bigList key is read and written one item at a time, so its schema is an item's
  await toInterface('ItemValues', itemKeys),
  `export const KEYS = ${toKeys(valueKeys)} satisfies KeyInfos`,
  `export const ITEMS_KEYS = ${toKeys(itemKeys)} satisfies ItemKeyInfos`,
].join('\n\n')
await writeFile(new URL('registry.generated.ts', dir), `${output}\n`)

function toInterface(name: string, keys: Definition[]) {
  const properties = Object.fromEntries(keys.map(({key, schema}) => [key, withoutMeta(schema)]))
  return compile({type: 'object', properties, required: Object.keys(properties)}, name, {
    bannerComment: '',
    additionalProperties: false,
    maxItems: -1,
    format: false,
    unknownAny: true,
  })
}

function withoutMeta({$schema: _schema, default: _default, ...schema}: JSONSchema) {
  return schema
}

function toKeys(keys: Definition[]) {
  const entries = keys.map(({key, levels, schema}) => {
    const info = {levels, defaultValue: schema.default ?? null}
    if (isItemList(schema)) return [key, {...info, list: true}]
    return [key, info]
  })
  return JSON.stringify(Object.fromEntries(entries))
}

// A list of items told apart by `ref`, like `manage.pinned.projects`, which the SDK edits as a list
function isItemList(schema: JSONSchema) {
  const items = schema.items
  return schema.type === 'array' && isSchema(items) && Boolean(items.properties?.['ref'])
}

function isSchema(value: unknown): value is JSONSchema {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function isNever(value: unknown) {
  return JSON.stringify(value) === '{"not":{}}'
}
